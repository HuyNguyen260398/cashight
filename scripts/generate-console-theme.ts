/**
 * Writes app/console-theme.generated.css from the Cloudscape theme in
 * app/components/console/console-theme.ts. Cloudscape's theming module is
 * client-only, so the stylesheet is generated here instead of at render time.
 * lib/__tests__/console-theme.test.ts fails when the output is stale.
 */
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { generateThemeStylesheet } from '@cloudscape-design/components/theming';
import { consoleTheme } from '../app/components/console/console-theme';

export const GENERATED_THEME_PATH = path.resolve(__dirname, '../app/console-theme.generated.css');

export function renderConsoleThemeCss(): string {
  return (
    '/* Generated by `pnpm theme:generate` from app/components/console/console-theme.ts — do not edit. */\n' +
    generateThemeStylesheet({ theme: consoleTheme }) +
    '\n'
  );
}

if (require.main === module) {
  writeFileSync(GENERATED_THEME_PATH, renderConsoleThemeCss());
  console.log(`wrote ${path.relative(process.cwd(), GENERATED_THEME_PATH)}`);
}
